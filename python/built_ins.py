#
# * "len" (for strings, lists, tuples, etc.)
print("len('Hello'):", len("Hello"))

# * "min", "max", "sum"
print("min(1, 2, 3):", min(1, 2, 3))
print("max(1, 2, 3):", max(1, 2, 3))
print("sum([1, 2, 3]):", sum([1, 2, 3]))

# * "round"
print("round(2.5):", round(2.5))
print("round(3.14159, 2):", round(3.14159, 2))

# * "abs"
print("abs(-5):", abs(-5))
